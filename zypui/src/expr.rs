//! 表达式 AST —— `.zypui` 里状态条件的唯一词汇表。
//!
//! # 表达力边界（设计定稿，2026-10-25 与用户对齐）
//!
//! 照 Slint 的**形状**（表达式写在 UI 文件里、由框架求值），但求值时机是
//! **每帧实例化期**：本框架每帧重建 Element 树，表达式天然每帧重算，
//! 不需要 Slint 那套常驻响应式属性引擎。词汇表：
//!
//! | 写法 | 含义 |
//! |---|---|
//! | `'text'` / `3.5` / `true` | 字面量 |
//! | `hover` / `press` | 当前实例 key 的悬停/按住（内置词，见 [`BUILTINS`]） |
//! | `name` | 组件实参或 `for` 变量（作用域链解析） |
//! | `@name` | 宿主绑定（路由、开关状态、文案外的应用数据） |
//! | `tr("key")` | i18n 取文案（唯一内置调用，其余的等真需求出现再加） |
//! | `==` `!=` `<` `<=` `>` `>=` | 比较（同类型才相等，跨类型恒 false） |
//! | `+` `-` | 数值加减；`+` 对两串是拼接 |
//! | `*` `/` | 数值乘除 |
//! | `!` `-`（前缀） | 非 / 取负 |
//! | `&&` `||` `?:` | 逻辑与或、三元 |
//!
//! 没有的：属性间引用（`parent.width` 之类）—— 那要布局值参与求值，
//! 时机在布局之后，与「实例化期求值」的定稿冲突。真出现需求再立项。
//!
//! # 身份用 `&'static str`
//!
//! 与整个 IR 一致：标识符来自解析（加载期泄漏一次），求值只比较不分配。

/// 二元运算符。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BinOp {
    /// `+`：数值加或字符串拼接。
    Add,
    /// `-`
    Sub,
    /// `*`
    Mul,
    /// `/`
    Div,
    /// `==`
    Eq,
    /// `!=`
    Ne,
    /// `<`
    Lt,
    /// `<=`
    Le,
    /// `>`
    Gt,
    /// `>=`
    Ge,
    /// `&&`
    And,
    /// `||`
    Or,
    /// `%`（取模；f32 语义，`b == 0` 得 0 —— 与除零同一降级）。
    Mod,
}

/// 表达式。
#[derive(Debug, Clone, PartialEq)]
pub enum Expr {
    /// 字符串字面量。
    LitS(&'static str),
    /// 数值字面量。
    LitF(f32),
    /// 布尔字面量。
    LitB(bool),
    /// 标识符：沿作用域链解析（`for` 变量 → 组件实参），未命中在
    /// **编译期**校验就报错（见 `zypuic`），运行期不会遇到未知标识符。
    Ref(&'static str),
    /// `@name`：宿主绑定。运行期查 [`crate::Host::binding`]，
    /// 未绑定的名字求值为假（编译期只警告不报错 —— 绑定表在宿主手里）。
    Binding(&'static str),
    /// 内置调用。目前只有 `tr(key)`。
    Call(&'static str, Vec<Expr>),
    /// 二元运算。
    Bin(BinOp, Box<Expr>, Box<Expr>),
    /// `!`
    Not(Box<Expr>),
    /// 前缀 `-`
    Neg(Box<Expr>),
    /// `cond ? a : b`
    Cond(Box<Expr>, Box<Expr>, Box<Expr>),
    /// `base.field`：记录字段访问。base 求值成 [`crate::Val::Rec`] 时按名
    /// 取字段，否则降级为假值（同「缺绑定判假」）。
    Field(Box<Expr>, &'static str),
}

/// 内置标识符（裸名字，不需要 `@`）。
///
/// - `hover` / `press`：当前实例 key 正被悬停/按住。当前实例 key 由
///   实例化器维护：进入带 key 的组件实例或元素时更新，子树共享 ——
///   与现状 Rust 控件「调用方把 hovered 传进构造器、构造器扇出给子节点」
///   是同一条数据流。
/// - `key`：当前实例 key 本身（字符串）。expander 家族的「可点区域 key =
///   实例 key」场景用（模板内固定 key 会同页撞名）。
pub const BUILTINS: &[&str] = &["hover", "press", "key"];

/// 内置调用名。
///
/// - `tr(key)`：i18n 文案。
/// - `min(a,b)` / `max(a,b)`：数值钳制（滑条填充宽那类内容几何）。
/// - `range(n)`：`0..n` 数值列表（固定个数的重复结构：指示点、色板行）。
/// - `str(x)`：数值 → 十进制串（经去重表 `&'static` 化；动态 key 的拼料）。
/// - `at(list, i)`：按下标取列表元素（分格布局：日历的 `r*7+c`）。
/// - `hover(k)` / `press(k)`：**指定 key** 的悬停/按住 —— 数据驱动列表的
///   逐项状态（`hover('td:00')`）；无参形式用内置词 `hover` / `press`。
pub const CALLS: &[&str] = &["tr", "min", "max", "range", "str", "at", "hover", "press"];
